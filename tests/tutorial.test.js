// Tutorial on a phone: every coach step, the training dive with touch controls, and saving "done".
const { open, game } = require('./helpers');
(async () => {
  const { browser, page, errors, ok } = await open({ mobile: true });
  await page.evaluate(() => localStorage.clear()); await page.reload();
  await page.waitForFunction(() => window.__ds && document.querySelector('#sheet .tabs')); await page.waitForTimeout(300);
  const coach = () => page.evaluate(() => { const c = document.getElementById('coach'); return c.hidden ? null : c.querySelector('p').textContent; });
  ok((await coach() || '').startsWith('Welcome'), 'tutorial starts on first launch');
  await page.click('[data-tut="cash"]'); ok((await page.$$('.spot')).length >= 1, 'salvage counter highlighted');
  await page.click('[data-tut="controls"]'); ok((await coach() || '').includes('tap the water'), 'controls step explains touch steering');
  await page.click('[data-tut="map"]'); ok((await coach() || '').includes('training dive'), 'dive map step');
  await page.click('[data-tut="dive"]'); await page.waitForTimeout(700);
  ok(await page.evaluate(() => __ds.run.D && __ds.run.D.tutorial), 'training dive started');
  ok(await page.evaluate(() => !document.getElementById('stick').hidden), 'thumb-stick visible on touch');
  ok((await coach() || '').includes('thumb-stick'), 'coach explains the thumb-stick');
  await game.tp(page, 0); await page.waitForTimeout(300);
  ok(await page.evaluate(() => !document.getElementById('act').hidden && document.getElementById('act').textContent === 'Scan'), 'Scan button appears near the target');
  await page.click('#act'); await page.waitForTimeout(150);
  ok((await coach() || '').startsWith('Read the question'), 'coach explains scanning');
  await game.answer(page, false); await page.waitForTimeout(100);
  ok((await coach() || '').includes('Back to exploring'), 'after answering, coach points to Back');
  await page.click('[data-enc="close"]'); await page.waitForTimeout(150);
  ok((await coach() || '').includes('salvage crate'), 'coach sends you to the crate');
  ok((await game.clear(page, 1, true)) === 'crate', 'crate sorted');
  ok((await coach() || '').includes('Redundancy Leech'), 'coach introduces the creature');
  await page.evaluate(() => { __ds.run.D.o2 = 0.5; }); await page.waitForTimeout(400);
  ok(await page.evaluate(() => __ds.run.D && __ds.run.D.o2 > 0), "can't black out during training");
  ok((await game.clear(page, 2, true)) === 'beast', 'baby leech repelled');
  ok((await coach() || '').includes('Training complete'), 'coach says to claim the bonus');
  await page.click('[data-act="claim"]'); await page.waitForTimeout(500);
  ok((await coach() || '').startsWith('Ascending banks'), 'result step');
  await page.click('[data-act="home"]'); await page.waitForTimeout(200);
  ok((await coach() || '').startsWith('The Fabricator'), 'fabricator step');
  await page.click('[data-tut="bay"]'); ok((await coach() || '').startsWith('The Sub Bay'), 'sub bay step');
  await page.click('[data-tut="bank"]'); ok((await coach() || '').startsWith('The Databank'), 'databank step');
  await page.click('[data-tut="go"]'); ok((await coach() || '').startsWith("You're ready"), 'final step');
  await page.click('[data-tut="done"]');
  const S = await page.evaluate(() => __ds.S);
  ok(S.tut === 'done' && !S.cleared.length && S.banked > 60, 'tutorial saved as done; zone not cleared; salvage banked: ' + S.banked);
  ok(errors.length === 0, 'no page errors ' + JSON.stringify(errors));
  await browser.close();
})();
